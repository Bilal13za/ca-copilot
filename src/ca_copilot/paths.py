"""Filesystem locations for CA Copilot.

All user data lives in ONE clearly-documented local data directory, never in
the source tree and never in a temp folder:

- Windows : %LOCALAPPDATA%\\CA Copilot        (e.g. C:\\Users\\Bilal\\AppData\\Local\\CA Copilot)
- macOS   : ~/Library/Application Support/CA Copilot
- Linux   : ~/.local/share/ca-copilot

Layout inside the data directory:

    config.json        application settings (safe defaults; user-editable)
    app.db             SQLite database (documents index, chats, notes, tasks, ...)
    documents/         imported file copies + per-document extracted text cache
    reports/           exported CSV/XLSX reports generated by the workbench
    backups/           backup archives created by the backup tool
    logs/              application log files
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

APP_NAME = "CA Copilot"


def data_dir() -> Path:
    """Return (creating if needed) the local application data directory."""
    override = os.environ.get("CA_COPILOT_DATA_DIR")
    if override:
        root = Path(override)
    elif os.name == "nt":
        base = os.environ.get("LOCALAPPDATA") or str(Path.home() / "AppData" / "Local")
        root = Path(base) / APP_NAME
    elif sys.platform == "darwin":
        root = Path.home() / "Library" / "Application Support" / APP_NAME
    else:
        root = Path.home() / ".local" / "share" / "ca-copilot"
    for sub in ("", "documents", "reports", "backups", "logs"):
        (root / sub).mkdir(parents=True, exist_ok=True)
    return root


def documents_dir() -> Path:
    return data_dir() / "documents"


def reports_dir() -> Path:
    return data_dir() / "reports"


def backups_dir() -> Path:
    return data_dir() / "backups"


def logs_dir() -> Path:
    return data_dir() / "logs"


def db_path() -> Path:
    return data_dir() / "app.db"


def config_path() -> Path:
    return data_dir() / "config.json"
